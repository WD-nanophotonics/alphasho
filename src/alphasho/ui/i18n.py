CATALOGS: dict[Language, dict[str, str]] = {
    Language.JAPANESE: _JA,
    Language.CHINESE: _ZH,
    Language.ENGLISH: _EN,
}


class Translator:
    def __init__(self, language: Language = Language.JAPANESE) -> None:
        self.language = language

    def set_language(self, language: Language) -> None:
        self.language = language

    def tr(self, key: str, **params: object) -> str:
        return CATALOGS[self.language][key].format(**params)

    def player(self, color: Color) -> str:
        return self.tr("black" if color is Color.BLACK else "white")

    def message(self, message: UiMessage) -> str:
        return self.tr(message.key, **message.format_params())

    def outcome(self, outcome: GameOutcome) -> str:
        reason_key = {
            OutcomeReason.CHECKMATE: "outcome_checkmate",
            OutcomeReason.REPETITION: "outcome_repetition",
            OutcomeReason.PERPETUAL_CHECK: "outcome_perpetual_check",
            OutcomeReason.SUPERIOR_REPETITION: "outcome_superior_repetition",
            OutcomeReason.RESIGNATION: "outcome_resignation",
            OutcomeReason.NYUGYOKU: "outcome_nyugyoku",
            OutcomeReason.TIMEOUT: "outcome_timeout",
            OutcomeReason.MOVE_LIMIT: "outcome_move_limit",
        }[outcome.reason]
        reason = self.tr(reason_key)
        if outcome.winner is None:
            return self.tr("draw_result", reason=reason)
        return self.tr("winner", player=self.player(outcome.winner), reason=reason)

    def rank_labels(self) -> tuple[str, ...]:
        if self.language is Language.ENGLISH:
            return tuple("abcdefghi")
        return tuple("一二三四五六七八九")
